-- Run this script in Supabase SQL Editor.
create table if not exists public.tournament_settings (
  id integer primary key check (id = 1),
  tournament_name text not null default 'Gramin Cricket',
  max_teams integer not null default 16 check (max_teams > 0),
  created_at timestamptz not null default now()
);
insert into public.tournament_settings (id, tournament_name, max_teams)
values (1, 'Gramin Cricket', 16)
on conflict (id) do nothing;

create table if not exists public.teams (
  id bigint generated by default as identity primary key,
  team_name text not null,
  village text not null,
  captain_name text not null,
  mobile text not null,
  manager_name text,
  status text not null default 'confirmed' check (status in ('confirmed','waiting')),
  created_at timestamptz not null default now()
);
create unique index if not exists teams_name_lower_unique on public.teams (lower(team_name));

-- This starter uses the backend service-role key; never put that key in frontend code.
alter table public.teams enable row level security;
alter table public.tournament_settings enable row level security;
